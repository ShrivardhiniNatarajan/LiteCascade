"""Build a Markdown + JSON evaluation report from run outputs.

python -m litecascade.eval.report --dataset fixture --results results --out reports/fixture
"""

import argparse
import json
from pathlib import Path

BASELINE_NAMES = {
    "teacher": "Teacher (CNN-BiLSTM)",
    "b1": "B1 L1-MLP",
    "b2": "B2 RF/XGB",
    "b3": "B3 LSTM",
    "b4": "B4 BiLSTM",
    "b5": "B5 PCA+BiLSTM+dynINT8",
    "b6": "B6 CNN-BiLSTM",
    "b7": "B7 DS-CNN",
    "b8": "B8 Tiny Transformer",
    "b9": "B9 BiGRU",
    "b10": "B10 TCN",
    "b11": "B11 ResNet-1D",
}


def _fmt(v, nd=4):
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def _ci(m, key):
    ci = m.get(f"{key}_95ci")
    return f" [{ci[0]:.3f}, {ci[1]:.3f}]" if ci else ""


def latest_baselines(results: Path, dataset: str) -> dict:
    found = {}
    for p in sorted(results.glob("*/metrics.json"), key=lambda p: p.stat().st_mtime):
        try:
            payload = json.loads(p.read_text())
        except Exception:
            continue
        m = payload.get("metrics", {})
        if m.get("dataset") == dataset and m.get("model") in BASELINE_NAMES:
            found[m["model"]] = m  # later files overwrite earlier ones
    return found


def latest_cascades(results: Path, dataset: str) -> dict:
    found = {}
    for p in sorted(results.glob("cascade_*/report.json"), key=lambda p: p.stat().st_mtime):
        rep = json.loads(p.read_text())
        cfg = rep.get("config", {})
        if cfg.get("dataset") != dataset or cfg.get("tag", "main") != "main":
            continue
        found[cfg.get("variant", "?")] = rep
    return found


def build_report(dataset: str, results="results", ablations: Path | None = None) -> tuple[str, dict]:
    results = Path(results)
    base = latest_baselines(results, dataset)
    casc = latest_cascades(results, dataset)
    synthetic = any(r.get("data_kind", "").startswith("SYNTHETIC") for r in casc.values()) or dataset.startswith("fixture")
    lines = [f"# LiteCascade evaluation report - dataset `{dataset}`", ""]
    if synthetic:
        lines += [
            "> **SYNTHETIC DATA.** Every number below comes from the small synthetic fixture generated by",
            "> `litecascade.data.synthetic`. It demonstrates that the pipeline runs end-to-end; it is **not** evidence",
            "> of detection performance on N-BaIoT, CICIoT2023, IoT-23 or real traffic.",
            "",
        ]
    lines += [
        "> Latency = wall-clock on the machine that produced this report (host CPU, PyTorch eager), **not** a",
        "> Raspberry Pi / MCU measurement. Sizes are serialized PyTorch state_dicts (they include pickle overhead).",
        "> LiteCascade latencies are for the final (INT8) model; PyTorch's INT8 kernels on this CPU carry per-op",
        '> overhead, so INT8 is not necessarily faster than FP32 here. "Measured speed-up" = mean per-window time of',
        "> always running both exits / mean time of real cascade inference (batch 1, same model).",
        "",
    ]
    if casc:
        any_rep = next(iter(casc.values()))
        w = any_rep["data"]["windows"]
        lines += ["## Data", "", "| split | windows | malicious | benign |", "|---|---|---|---|"]
        lines += [
            f"| {s} | {w[s]['windows']} | {w[s]['malicious']} | {w[s]['benign']} |" for s in ("train", "val", "calib", "test")
        ]
        lines += [
            "",
            f"Split mode: `{any_rep['data']['split_mode']}`; groups: `{json.dumps(any_rep['data']['split_groups'])}`",
            "",
        ]

    # ---- main comparison
    lines += [
        "## Main comparison (test split)",
        "",
        "| Model | macro-F1 [95% CI] | Malicious recall | FPR | Params | Size FP32 KB | Size INT8 KB | MACs / window "
        "| p50 ms (host) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for key, label in BASELINE_NAMES.items():
        if key not in base:
            continue
        m = base[key]
        lines.append(
            f"| {label} | {_fmt(m['f1_macro'])}{_ci(m, 'f1_macro')} | {_fmt(m['recall_malicious'])} | {_fmt(m['fpr'])} | "
            f"{m.get('params')} | {_fmt(m.get('size_fp32_kb'), 1)} | {_fmt(m.get('size_int8_kb'), 1)} | "
            f"{_fmt(m.get('macs'))} | {_fmt(m.get('latency_p50_ms'), 3)} |"
        )
    for variant, rep in sorted(casc.items()):
        first, final = rep["stages"][0], rep["stages"][-1]
        c = final["test"]["cascade"]
        prof_final = final["profile"]
        exp_macs = prof_final.get("expected_macs")
        lines.append(
            f"| LiteCascade-{variant} ({final['stage']}) | {_fmt(c['f1_macro'])} | {_fmt(c['recall_malicious'])} | "
            f"{_fmt(c['fpr'])} | "
            f"{final['profile']['params']['total']} | {_fmt(first['profile']['size_kb_serialized'], 1)} | "
            f"{_fmt(final['profile']['size_kb_serialized'], 1) if final['quantization'] != 'none' else 'n/a'} | "
            f"E={_fmt(exp_macs, 0)} (full {prof_final.get('macs_full')}) | "
            f"{_fmt(final['profile']['latency_sentinel_path']['p50_ms'], 3)} Sentinel path / "
            f"{_fmt(final['profile']['latency_full_path']['p50_ms'], 3)} full path |"
        )
    lines.append("")

    # ---- per stage
    for variant, rep in sorted(casc.items()):
        lines += [
            f"## LiteCascade-{variant}: compression chain stages (test split)",
            "",
            "| Stage | Cascade F1 | Recall | Sentinel-only F1 | Analyst-only F1 | rho (exit rate) | rho @1% / 5% prev. | "
            "Exit-induced miss rate | E[MACs] | Size KB | measured speed-up vs full (host) |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for st in rep["stages"]:
            t, p = st["test"], st["profile"]
            rw = t["rho_reweighted"]
            lines.append(
                f"| {st['stage']} | {_fmt(t['cascade']['f1_macro'])} | {_fmt(t['cascade']['recall_malicious'])} | "
                f"{_fmt(t['sentinel_only']['f1_macro'])} | {_fmt(t['analyst_only']['f1_macro'])} | "
                f"{_fmt(t['rho_raw'], 3)} | "
                f"{_fmt(rw.get('1pct'), 3)} / {_fmt(rw.get('5pct'), 3)} | {_fmt(t['exit_induced_miss_rate'])} | "
                f"{_fmt(p.get('expected_macs'), 0)} | {_fmt(p['size_kb_serialized'], 1)} | "
                f"{_fmt(p.get('measured_speedup'), 2)}x |"
            )
        g = rep["stages"][-1]["gate"]
        lines += [
            "",
            f"Final gate: T1={_fmt(g.get('T1'))}, T2={_fmt(g.get('T2'))}, tau_b={_fmt(g.get('tau_b'))}, "
            f"tau_m={_fmt(g.get('tau_m'))}, "
            f"epsilon={g.get('epsilon')}, alpha={g.get('alpha')}, N_m={g.get('N_m')} (need >= {g.get('min_N_m')}), "
            f"m_calib={g.get('m_calib')}, U_CP={_fmt(g.get('ucp_calib'))}, feasible={g.get('feasible')}.",
            "",
            f"Live cascade inference check (final stage): {json.dumps(rep['stages'][-1]['test']['live_inference'])}",
            "",
        ]
        if rep.get("teacher"):
            lines += [f"Teacher test macro-F1: {_fmt(rep['teacher']['test']['f1_macro'])}", ""]

    abl = None
    if ablations and Path(ablations).exists():
        abl = json.loads(Path(ablations).read_text())
        lines += [
            "## Ablations (final stage of each configuration, test split)",
            "",
            "| Configuration | Cascade F1 | Recall | rho | Exit-induced miss rate | Analyst-only F1 | Sentinel-only F1 |",
            "|---|---|---|---|---|---|---|",
        ]
        for row in abl:
            lines.append(
                f"| {row['name']} | {_fmt(row['cascade_f1'])} | {_fmt(row['recall'])} | {_fmt(row['rho'], 3)} | "
                f"{_fmt(row['exit_miss'])} | {_fmt(row['analyst_f1'])} | {_fmt(row['sentinel_f1'])} |"
            )
        lines.append("")

    lines += [
        "## Not measured here",
        "",
        "- On-device latency / RAM / energy on Raspberry Pi or MCU (no hardware in this environment).",
        "- TFLite / TFLite-Micro export, Malimg byteplot adapter, leave-one-family-out and perturbation robustness tables.",
        "",
    ]
    return "\n".join(lines), {"baselines": base, "cascades": casc, "ablations": abl, "synthetic": synthetic}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default="fixture")
    ap.add_argument("--results", default="results")
    ap.add_argument("--ablations", default=None)
    ap.add_argument("--out", default=None, help="output prefix, e.g. reports/fixture -> .md and .json")
    args = ap.parse_args(argv)
    md, payload = build_report(args.dataset, args.results, Path(args.ablations) if args.ablations else None)
    out = Path(args.out or f"reports/{args.dataset}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".md").write_text(md, encoding="utf-8")
    out.with_suffix(".json").write_text(json.dumps(payload, indent=2, default=float), encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
